// Package models holds one Go struct per database table, like Laravel's
// Eloquent models. The `gorm:"..."` tags tell GORM the column details and
// the `json:"..."` tags are never used for API output (resources do that).
package models

import (
	"time"

	"gorm.io/datatypes"
)

// User is a Tribe customer (table: users).
type User struct {
	ID              string     `gorm:"primaryKey" json:"id"`
	Email           string     `json:"email"`
	PasswordHash    string     `json:"-"`
	FirstName       string     `json:"first_name"`
	LastName        string     `json:"last_name"`
	Tag             string     `json:"tag"`
	Phone           *string    `json:"phone"`
	PhoneVerifiedAt *time.Time `json:"phone_verified_at"`
	Country         string     `json:"country"`
	DateOfBirth     *time.Time `json:"date_of_birth"`
	Address         *string    `json:"address"`
	Status          string     `json:"status"` // active | frozen | closed
	KycTier         int        `json:"kyc_tier"`
	KycStatus       string     `json:"kyc_status"`
	// Not columns: filled from the open KYC submission (account.AttachOpenKyc)
	// so the profile tells the app which tier is in review and since when.
	KycPendingTier        *int           `gorm:"-" json:"-"`
	KycSubmittedAt        *time.Time     `gorm:"-" json:"-"`
	GlobalAccountsStatus  string         `json:"global_accounts_status"`
	World                 *string        `json:"world"`
	OnboardingCompletedAt *time.Time     `json:"onboarding_completed_at"`
	ReferralCode          string         `json:"referral_code"`
	ReferredByUserID      *string        `json:"referred_by_user_id"`
	HeardFrom             *string        `json:"heard_from"`
	Labels                datatypes.JSON `json:"labels"`
	BiometricsEnabled     bool           `json:"biometrics_enabled"`
	TwoFactorEnabled      bool           `json:"two_factor_enabled"`
	TagChangedAt          *time.Time     `json:"tag_changed_at"`
	EmailVerifiedAt       *time.Time     `json:"email_verified_at"`
	LastActiveAt          *time.Time     `json:"last_active_at"`
	Version               int            `json:"version"`
	CreatedAt             time.Time      `json:"created_at"`
	UpdatedAt             time.Time      `json:"updated_at"`
}

// FullName returns "First Last".
func (user User) FullName() string {
	return user.FirstName + " " + user.LastName
}

// UserDevice is one phone a user signed in with (table: user_devices).
type UserDevice struct {
	ID           string     `gorm:"primaryKey" json:"id"`
	UserID       string     `json:"user_id"`
	DeviceImei   string     `json:"device_imei"`
	Name         string     `json:"name"`
	Platform     string     `json:"platform"`
	Model        string     `json:"model"`
	AppVersion   string     `json:"app_version"`
	Status       string     `json:"status"`                         // pending | active | replaced | revoked
	ActiveUserID *string    `gorm:"<-:false" json:"active_user_id"` // generated by MySQL; never written by Go
	LastSeenAt   *time.Time `json:"last_seen_at"`
	ActivatedAt  *time.Time `json:"activated_at"`
	ReplacedAt   *time.Time `json:"replaced_at"`
	CreatedAt    time.Time  `json:"created_at"`
	UpdatedAt    time.Time  `json:"updated_at"`
}

// Device statuses.
const (
	DeviceStatusPending  = "pending"
	DeviceStatusActive   = "active"
	DeviceStatusReplaced = "replaced"
	DeviceStatusRevoked  = "revoked"
)

// UserSession is a signed-in session on one device (table: user_sessions).
type UserSession struct {
	ID            string     `gorm:"primaryKey" json:"id"`
	UserID        string     `json:"user_id"`
	DeviceID      string     `json:"device_id"`
	IPAddress     string     `gorm:"column:ip_address" json:"ip_address"`
	UserAgent     string     `json:"user_agent"`
	LastUsedAt    time.Time  `json:"last_used_at"`
	ExpiresAt     time.Time  `json:"expires_at"`
	RevokedAt     *time.Time `json:"revoked_at"`
	RevokedReason *string    `json:"revoked_reason"`
	CreatedAt     time.Time  `json:"created_at"`
}

// RefreshToken is the hashed long-lived token (table: refresh_tokens).
type RefreshToken struct {
	ID        string     `gorm:"primaryKey" json:"id"`
	SessionID string     `json:"session_id"`
	TokenHash string     `json:"-"`
	ExpiresAt time.Time  `json:"expires_at"`
	UsedAt    *time.Time `json:"used_at"`
	CreatedAt time.Time  `json:"created_at"`
}

// EmailVerification is a 6-digit email code (table: email_verifications).
type EmailVerification struct {
	ID                    string     `gorm:"primaryKey" json:"id"`
	Email                 string     `json:"email"`
	Purpose               string     `json:"purpose"`
	CodeHash              string     `json:"-"`
	Attempts              int        `json:"attempts"`
	ExpiresAt             time.Time  `json:"expires_at"`
	VerifiedAt            *time.Time `json:"verified_at"`
	VerificationTokenHash *string    `json:"-"`
	ConsumedAt            *time.Time `json:"consumed_at"`
	CreatedAt             time.Time  `json:"created_at"`
}

// PhoneVerification is a 6-digit SMS code (table: phone_verifications).
type PhoneVerification struct {
	ID         string     `gorm:"primaryKey" json:"id"`
	UserID     string     `json:"user_id"`
	Phone      string     `json:"phone"`
	CodeHash   string     `json:"-"`
	Attempts   int        `json:"attempts"`
	ExpiresAt  time.Time  `json:"expires_at"`
	VerifiedAt *time.Time `json:"verified_at"`
	CreatedAt  time.Time  `json:"created_at"`
}

// DeviceVerification is the email code for a new phone (table: device_verifications).
type DeviceVerification struct {
	ID         string     `gorm:"primaryKey" json:"id"`
	UserID     string     `json:"user_id"`
	DeviceID   string     `json:"device_id"`
	CodeHash   string     `json:"-"`
	Attempts   int        `json:"attempts"`
	ExpiresAt  time.Time  `json:"expires_at"`
	VerifiedAt *time.Time `json:"verified_at"`
	CreatedAt  time.Time  `json:"created_at"`
}

// UserPin is the hashed payment PIN (table: user_pins).
type UserPin struct {
	UserID         string     `gorm:"primaryKey" json:"user_id"`
	PinHash        string     `json:"-"`
	FailedAttempts int        `json:"failed_attempts"`
	LockedUntil    *time.Time `json:"locked_until"`
	UpdatedAt      time.Time  `json:"updated_at"`
}

// PushToken is an Expo push token (table: push_tokens).
type PushToken struct {
	ID        string    `gorm:"primaryKey" json:"id"`
	UserID    string    `json:"user_id"`
	Token     string    `json:"token"`
	Platform  string    `json:"platform"`
	CreatedAt time.Time `json:"created_at"`
}

// AdminUser is someone who uses the admin panel (table: admin_users).
type AdminUser struct {
	ID           string     `gorm:"primaryKey" json:"id"`
	Name         string     `json:"name"`
	Email        string     `json:"email"`
	PasswordHash string     `json:"-"`
	Color        string     `json:"color"`
	Status       string     `json:"status"` // active | suspended
	LastLoginAt  *time.Time `json:"last_login_at"`
	CreatedBy    *string    `json:"created_by"`
	Version      int        `json:"version"`
	CreatedAt    time.Time  `json:"created_at"`
	UpdatedAt    time.Time  `json:"updated_at"`
}

// AdminUserPermission is one permission an admin has (table: admin_user_permissions).
type AdminUserPermission struct {
	AdminUserID string `gorm:"primaryKey" json:"admin_user_id"`
	Permission  string `gorm:"primaryKey" json:"permission"`
}

// AdminSession is a signed-in admin session (table: admin_sessions).
type AdminSession struct {
	ID          string     `gorm:"primaryKey" json:"id"`
	AdminUserID string     `json:"admin_user_id"`
	IPAddress   string     `gorm:"column:ip_address" json:"ip_address"`
	UserAgent   string     `json:"user_agent"`
	ExpiresAt   time.Time  `json:"expires_at"`
	RevokedAt   *time.Time `json:"revoked_at"`
	CreatedAt   time.Time  `json:"created_at"`
}

// AuditLog records one admin write (table: audit_logs).
type AuditLog struct {
	ID          string         `gorm:"primaryKey" json:"id"`
	AdminUserID *string        `json:"admin_user_id"`
	AdminName   string         `json:"admin_name"`
	Action      string         `json:"action"`
	Target      string         `json:"target"`
	Summary     string         `json:"summary"`
	BeforeData  datatypes.JSON `json:"before_data"`
	AfterData   datatypes.JSON `json:"after_data"`
	CreatedAt   time.Time      `json:"created_at"`
}
